import type { ProjectState, TestReport } from "../types";
import { duration } from "../lib/format";
import { Callout, Panel, Stat, StatGrid, Tag, Waiting } from "../components/ui";

const PHASE_LABEL: Record<TestReport["phase"], string> = {
  baseline: "Baseline",
  post_transform: "After transformation",
  post_repair: "After repair",
};

export function Tests({ state }: { state: ProjectState }) {
  const latest = state.test_runs.at(-1);
  const baseline = state.baseline ?? state.test_runs.find((report) => report.phase === "baseline");
  if (!baseline) return <Panel title="Tests"><Waiting what="Test results" /></Panel>;
  const regressions = latest && state.baseline ? state.baseline_pass_set.filter((id) => !latest.passed.includes(id)) : [];

  return (
    <div className="view-stack">
      <StatGrid>
        <Stat label="Frozen baseline" value={state.baseline_pass_set.length} />
        <Stat label="Passing now" value={latest?.passed.length ?? 0} />
        <Stat label="Regressions" value={regressions.length} />
        <Stat label="Test runs" value={state.test_runs.length} />
      </StatGrid>
      {regressions.length > 0 && (
        <Callout tone="bad" title={`${regressions.length} baseline test${regressions.length === 1 ? "" : "s"} no longer pass`}>
          <ul className="plain-list mono">{regressions.slice(0, 20).map((id) => <li key={id}>{id}</li>)}</ul>
        </Callout>
      )}
      <ReportPanel title={state.baseline ? "Baseline" : "Baseline attempt"} report={baseline} />
      {latest && latest !== baseline && <ReportPanel title={`Latest · ${PHASE_LABEL[latest.phase]}`} report={latest} />}
      <Panel title="Repair history">
        {state.repairs.length ? (
          <ol className="repair-list">
            {state.repairs.map((repair) => (
              <li key={repair.iteration}>
                <span className="step-id">R{repair.iteration}</span>
                <span>{repair.diagnosis}</span>
                <span className="muted numeric">{repair.failing_before} → {repair.failing_after ?? "…"} failing</span>
              </li>
            ))}
          </ol>
        ) : (
          <p className="empty-inline">No repairs were needed.</p>
        )}
      </Panel>
    </div>
  );
}

function ReportPanel({ title, report }: { title: string; report: TestReport }) {
  const failures = [...report.failed, ...report.errored];
  const ranNothing = report.install_ok && !report.passed.length && !failures.length;
  const tone = !report.install_ok || failures.length ? "bad" : ranNothing ? "warn" : "good";
  const label = !report.install_ok ? "Install failed" : failures.length ? `${failures.length} failing` : ranNothing ? "No tests ran" : "Passing";
  return (
    <Panel title={title} actions={<><span className="muted">{duration(report.duration_s)}</span><Tag tone={tone}>{label}</Tag></>}>
      <p className="test-counts">
        <span>{report.passed.length} passed</span>
        <span>{failures.length} failed</span>
        <span>{report.skipped.length} skipped</span>
        {report.typecheck_errors !== null && <span>{report.typecheck_errors} type errors</span>}
        {report.lint_issues !== null && <span>{report.lint_issues} lint issues</span>}
      </p>
      {!report.install_ok && (
        <>
          <p className="prose">Dependencies could not be installed in the sandbox, so no tests ran. Install output:</p>
          <pre className="log">{report.install_log_tail || "No install output was captured."}</pre>
        </>
      )}
      {ranNothing && (
        <p className="prose">Dependencies installed, but the repository has no runnable test suite or build check (for example only npm's placeholder <code className="code-inline">no test specified</code> script), and characterization tests could not be generated for this stack.</p>
      )}
      {report.generated_tests && <p className="muted">Includes characterization tests generated by ReForge.</p>}
      {failures.map((failure) => (
        <details key={failure.test_id} className="disclosure disclosure-bad">
          <summary><span className="mono">{failure.test_id}</span> — {failure.message}</summary>
          <pre className="log">{failure.traceback_excerpt}</pre>
        </details>
      ))}
      {report.passed.length > 0 && (
        <details className="disclosure">
          <summary>Passed tests ({report.passed.length})</summary>
          <ul className="test-ids">{report.passed.map((id) => <li key={id}>{id}</li>)}</ul>
        </details>
      )}
      {report.skipped.length > 0 && (
        <details className="disclosure">
          <summary>Skipped tests ({report.skipped.length})</summary>
          <ul className="test-ids">{report.skipped.map((id) => <li key={id}>{id}</li>)}</ul>
        </details>
      )}
    </Panel>
  );
}
